{
    return sizeof catalog / sizeof catalog[0];
}

enum folio_theme folio_theme_at(size_t index)
{
    return (enum folio_theme)index;
}

const char *_Nonnull folio_theme_name(enum folio_theme theme)
{
    return catalog[theme].name;
}

const struct theme_palette *_Nonnull folio_theme_palette(enum folio_theme theme)
{
    return &catalog[theme].palette;
}
