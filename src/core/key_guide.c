static_assert(sizeof rows / sizeof rows[0] <= key_guide_capacity);

size_t key_guide_count(void)
{
    return sizeof rows / sizeof rows[0];
}
const struct key_guide *_Nonnull key_guide_at(size_t index)
{
    return &rows[index];
}
enum ui_text key_guide_group(const struct key_guide *_Nonnull row)
{
    return row->group;
}
const char *_Nonnull key_guide_description(const struct key_guide *_Nonnull row,
                                           enum folio_language language)
{
    return ui_text_line(row->description, language);
}
static const char *_Nonnull key_text(const struct key_guide *_Nonnull row,
                                     enum folio_language language)
{
    switch (row->source)
    {
    case KEY_GUIDE_TEXT:
        return ui_text_line(row->text, language);
    case KEY_GUIDE_COMMAND:
        return folio_shortcut_command_hint(row->command, language);
    case KEY_GUIDE_ACTION:
        return folio_shortcut_action_hint(row->action, language);
    case KEY_GUIDE_EX:
        return folio_command_alias(row->command, 0);
    }
    return "";
}
enum ui_text_format_outcome key_guide_key(const struct key_guide *_Nonnull row,
                                          enum folio_language language, char *_Nonnull out,
                                          size_t capacity)
{
    struct ui_text_request request = {.id = row->source == KEY_GUIDE_EX ? UI_TEXT_MENU_EX_HINT
                                                                        : UI_TEXT_KEYS_VALUE,
                                      .language = language,
                                      .name = key_text(row, language)};
    if (row->source == KEY_GUIDE_EX && folio_command_alias_count(row->command) > 1)
    {
        request.id = UI_TEXT_KEYS_EX_ALIASES;
        request.from = folio_command_alias(row->command, 1);
    }
    return ui_text_format(&request, out, capacity);
}
enum ui_text_format_outcome key_guide_name(const struct key_guide *_Nonnull row,
                                           enum folio_language language, char *_Nonnull out,
                                           size_t capacity)
{
    char key[256];
    if (key_guide_key(row, language, key, sizeof key) != UI_TEXT_FORMAT_READY)
        return UI_TEXT_FORMAT_TOO_LONG;
    struct ui_text_request request = {.id = key[0] == '\0' ? UI_TEXT_KEYS_NOTE_NAME
                                                           : UI_TEXT_KEYS_NAME,
                                      .language = language,
                                      .name = ui_text_line(row->group, language),
                                      .from = key,
                                      .to = key_guide_description(row, language)};
    return ui_text_format(&request, out, capacity);
}
