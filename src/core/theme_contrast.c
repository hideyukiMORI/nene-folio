constexpr size_t ground_limit = 4;

static double luminance(struct rgb_color color)
{
    return 0.2126 * linear_channels[color.red] + 0.7152 * linear_channels[color.green] +
           0.0722 * linear_channels[color.blue];
}

double theme_contrast_ratio(struct rgb_color first, struct rgb_color second)
{
    double left = luminance(first);
    double right = luminance(second);
    double high = left > right ? left : right;
    double low = left > right ? right : left;
    return (high + 0.05) / (low + 0.05);
}

/* 役割ごとに線が接する地。数を返す（全値のswitch・C-002）。 */
static size_t line_grounds(const struct theme_palette *_Nonnull palette, enum theme_line line,
                           struct rgb_color *_Nonnull out)
{
    switch (line)
    {
    case THEME_LINE_HOVER:
    case THEME_LINE_FOCUS_ITEM:
        out[0] = palette->window;
        out[1] = palette->pane;
        return 2;
    case THEME_LINE_FOCUS:
        out[0] = palette->window;
        out[1] = palette->pane;
        out[2] = palette->dialog_surface;
        return 3;
    case THEME_LINE_FOCUS_SELECTED:
        out[0] = palette->selected_background;
        return 1;
    case THEME_LINE_FOCUS_PRIMARY:
        out[0] = palette->chip_background;
        return 1;
    case THEME_LINE_FIELD:
    case THEME_LINE_FIELD_FOCUS:
        out[0] = palette->window;
        out[1] = palette->pane;
        out[2] = palette->dialog_surface;
        out[3] = palette->dialog_control;
        return ground_limit;
    }
    return 0;
}

/* 役割の既定の線（「枠が接する地の上で使う字の色」）。 */
static struct rgb_color line_preferred(const struct theme_palette *_Nonnull palette,
                                       enum theme_line line)
{
    switch (line)
    {
    case THEME_LINE_HOVER:
    case THEME_LINE_FIELD:
        return palette->header_text;
    case THEME_LINE_FOCUS:
    case THEME_LINE_FOCUS_ITEM:
    case THEME_LINE_FIELD_FOCUS:
        return palette->current_text;
    case THEME_LINE_FOCUS_SELECTED:
        return palette->selected_text;
    case THEME_LINE_FOCUS_PRIMARY:
        return palette->chip_text;
    }
    return palette->current_text;
}

static double weakest(struct rgb_color ink, const struct rgb_color *_Nonnull grounds, size_t count)
{
    double lowest = 21.0;
    for (size_t index = 0; index < count; ++index)
    {
        double ratio = theme_contrast_ratio(ink, grounds[index]);
        lowest = ratio < lowest ? ratio : lowest;
    }
    return lowest;
}

struct rgb_color theme_contrast_line(const struct theme_palette *_Nonnull palette,
                                     enum theme_line line)
{
    struct rgb_color grounds[ground_limit] = {};
    size_t count = line_grounds(palette, line, grounds);
    const struct rgb_color candidates[] = {
        line_preferred(palette, line), palette->current_text,  palette->category_text,
        palette->editor_text,          palette->selected_text, palette->note_text,
        palette->header_text,
    };
    struct rgb_color best = candidates[0];
    double best_ratio = 0.0;
    for (size_t index = 0; index < sizeof candidates / sizeof candidates[0]; ++index)
    {
        double ratio = weakest(candidates[index], grounds, count);
        if (ratio >= theme_contrast_line_minimum)
        {
            return candidates[index];
        }
        if (ratio > best_ratio)
        {
            best = candidates[index];
            best_ratio = ratio;
        }
    }
    return best;
}
