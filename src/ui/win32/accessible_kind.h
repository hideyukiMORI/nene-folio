#ifndef NENEFOLIO_ACCESSIBLE_KIND_H
#define NENEFOLIO_ACCESSIBLE_KIND_H

/* 自前要素とkeyboardの到達先。FILTER/BODYはnative providerのままで公開する。
 * 兄弟の並びは列挙の順で、UIA の兄弟順と群の中の矢印の巡回がこの順を使う（#349）。 */
enum accessible_kind : unsigned char
{
    ACCESSIBLE_WINDOW,
    ACCESSIBLE_DRAWER,
    ACCESSIBLE_HEADER,
    ACCESSIBLE_NEW_NOTE,
    ACCESSIBLE_LAYOUT_GROUP,
    ACCESSIBLE_LAYOUT_DRAWER,
    ACCESSIBLE_LAYOUT_BOTH,
    ACCESSIBLE_LAYOUT_NOTE,
    ACCESSIBLE_LAYOUT_CHOOSER,
    ACCESSIBLE_HELP,
    ACCESSIBLE_SETTINGS,
    ACCESSIBLE_MINIMIZE,
    ACCESSIBLE_MAXIMIZE,
    ACCESSIBLE_CLOSE,
    ACCESSIBLE_SPLITTER,
    ACCESSIBLE_PANE_TOOLS,
    ACCESSIBLE_BREADCRUMB,
    ACCESSIBLE_MODE_GROUP,
    ACCESSIBLE_VIEW,
    ACCESSIBLE_EDIT,
    /* ノートの上部を畳む・戻す山形の釦（#1264）。頭の帯の右端。 */
    ACCESSIBLE_NOTE_HEADER,
    ACCESSIBLE_ACTION_GROUP,
    ACCESSIBLE_SAVE,
    ACCESSIBLE_FIND,
    ACCESSIBLE_MENU,
    ACCESSIBLE_TAG_EDIT,
    ACCESSIBLE_FILTER_GROUP,       /* 絞り込みの札の行（#1199）。子は下の 4 つで、列挙で連続 */
    ACCESSIBLE_FILTER_FAVORITES,   /* お気に入りの札（Toggle） */
    ACCESSIBLE_FILTER_TAG,         /* タグごとの札（#1247）。番号とタグの条件の改訂で 1 つを指す */
    ACCESSIBLE_FILTER_MORE,        /* 畳んだタグの「+N」。畳んだ分があるときだけある */
    ACCESSIBLE_TAG_FILTER,         /* タグの面を開く札 */
    ACCESSIBLE_FILTER_MATCH_GROUP, /* タグの条件の 2 択（#1249）。タグが 2 つ以上のときだけある */
    ACCESSIBLE_FILTER_MATCH_ALL,   /* すべて含む */
    ACCESSIBLE_FILTER_MATCH_ANY,   /* いずれか */
    ACCESSIBLE_FILTER_CLEAR,       /* 「× 解除」。条件が効いているときだけある */
    /* 検索の範囲の 2 択（#1292）。条件と検索語の両方があるときだけある。画面と Tab の順のとおり、
     * 解除の後 */
    ACCESSIBLE_SEARCH_SCOPE_GROUP,
    ACCESSIBLE_SEARCH_SCOPE_ALL,      /* すべてのノート */
    ACCESSIBLE_SEARCH_SCOPE_FILTERED, /* 絞り込みの中 */
    ACCESSIBLE_INDEX_COUNT, /* 見出しの行（「カテゴリ」と数）。名前は「カテゴリ k ・ ノート n」 */
    ACCESSIBLE_NEW_CATEGORY,
    ACCESSIBLE_TREE,
    ACCESSIBLE_CATEGORY,
    ACCESSIBLE_NOTE,
    ACCESSIBLE_FILTER,
    ACCESSIBLE_BODY,
    ACCESSIBLE_OUTLINE,
    ACCESSIBLE_OUTLINE_ITEM,
    ACCESSIBLE_MINIMAP,
    ACCESSIBLE_NOTICE,
    ACCESSIBLE_GUIDE,
    ACCESSIBLE_SURFACE,
    ACCESSIBLE_SURFACE_TABS,
    ACCESSIBLE_SURFACE_TAB,
    ACCESSIBLE_SURFACE_LIST,
    ACCESSIBLE_SURFACE_CHOICE,
    ACCESSIBLE_SURFACE_LANGUAGE,
    ACCESSIBLE_SURFACE_TOGGLE,
    ACCESSIBLE_SURFACE_BUTTON,
    ACCESSIBLE_SURFACE_TEXT,
    ACCESSIBLE_SURFACE_HELP,
    ACCESSIBLE_SURFACE_STATUS,
    ACCESSIBLE_COMMAND_INPUT,
    ACCESSIBLE_REPLACE_PATTERN,
    ACCESSIBLE_REPLACE_TEXT,
    ACCESSIBLE_DISCOVERY_PREVIEW
};

#endif
